# Extracts content display names from a Mindustry bundle.
#   .\extract-content-names.ps1 -Source .ref\tmp\game_bundle_zh.properties -Output i18n\content_zh_CN.properties
#
# Mindustry resolves UnlockableContent#localizedName from "<contentType>.<name>.name"
# (see UnlockableContent.java line 90). On a dedicated server Core.bundle has no such keys, so
# localizedName silently falls back to the internal name; the plugin ships this subset instead.

param(
    [Parameter(Mandatory = $true)][string] $Source,
    [Parameter(Mandatory = $true)][string] $Output
)

$ErrorActionPreference = "Stop"
$types = 'item', 'block', 'liquid', 'unit', 'sector', 'status', 'weather', 'planet'
$pattern = '^\s*(' + ($types -join '|') + ')\.[A-Za-z0-9_\-]+\.name\s*='

$text = [System.Text.Encoding]::UTF8.GetString([System.IO.File]::ReadAllBytes($Source))
$lines = $text -split "`r?`n" | Where-Object { $_ -match $pattern }

$header = @(
    '# Generated by deploy/extract-content-names.ps1 from the Mindustry v160.7 bundle.',
    '# Only the content display names are kept; the plugin uses them because Core.bundle has no',
    '# content keys on a dedicated server and UnlockableContent#localizedName falls back to the id.'
)

$directory = Split-Path -Parent $Output
if ($directory -and -not (Test-Path $directory)) { New-Item -ItemType Directory -Force -Path $directory | Out-Null }

$all = @($header) + ($lines | Sort-Object)
[System.IO.File]::WriteAllLines((Resolve-Path -LiteralPath (Split-Path -Parent $Output)).Path + '\' + (Split-Path -Leaf $Output), $all, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "wrote $($lines.Count) content names to $Output"
